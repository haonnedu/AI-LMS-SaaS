"""Disposable M0 migration and outage checks. Never operates on the default stack."""

import argparse
import json
import os
import re
import secrets
import socket
import subprocess
import time
from datetime import UTC, datetime
from pathlib import Path
from urllib.error import HTTPError, URLError
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
PORT_NAMES = ("POSTGRES_PORT", "REDIS_PORT", "API_PORT", "FRONTEND_PORT")
IDENTITY_TABLES = ["users", "workspace_members", "workspaces"]
ROUTES = (
    "/",
    "/library",
    "/classes",
    "/settings",
    "/login",
    "/lessons",
    "/assessments",
    "/student",
    "/school",
    "/admin",
    "/analytics",
)


def isolated_environment(values):
    """Compose shell values otherwise override --env-file, including project/ports."""
    env = {k: v for k, v in os.environ.items() if not k.upper().startswith("COMPOSE_")}
    for key in values:
        env.pop(key, None)
    env["COMPOSE_DISABLE_ENV_FILE"] = "1"
    return env


def free_ports(count):
    sockets = []
    try:
        for _ in range(count):
            item = socket.socket()
            sockets.append(item)
            item.bind(("127.0.0.1", 0))
        return [item.getsockname()[1] for item in sockets]
    finally:
        for item in sockets:
            item.close()


def http(url):
    try:
        with urlopen(url, timeout=8) as response:
            return response.status, response.read().decode("utf-8")
    except HTTPError as exc:
        return exc.code, exc.read().decode("utf-8")


def wait_http(url, status, checks=None, seconds=90):
    deadline = time.monotonic() + seconds
    while time.monotonic() < deadline:
        try:
            actual, body = http(url)
            if actual == status and (checks is None or json.loads(body).get("checks") == checks):
                return body
        except (URLError, TimeoutError, ConnectionError, ValueError):
            pass
        time.sleep(1)
    raise RuntimeError(f"Expected HTTP {status} and checks={checks} at {url}")


def assert_project(project):
    if not re.fullmatch(r"eduvia-m0-\d{8}t\d{6}z-[a-f0-9]{8}", project):
        raise ValueError("Refusing operation on a project not generated by this verifier")


class Verification:
    def __init__(self):
        stamp = datetime.now(UTC).strftime("%Y%m%dt%H%M%Sz").lower()
        self.project = f"eduvia-m0-{stamp}-{secrets.token_hex(4)}"
        assert_project(self.project)
        self.directory = ROOT / "tmp" / self.project
        self.directory.mkdir(parents=True)
        ports = free_ports(4)
        self.values = dict(
            zip(
                PORT_NAMES,
                map(str, ports),
                strict=True,
            )
        )
        self.values.update(
            POSTGRES_DB="eduvia_m0",
            POSTGRES_USER="eduvia_m0",
            POSTGRES_PASSWORD=secrets.token_hex(24),
        )
        self.env_file = self.directory / "compose.env"
        self.env_file.write_text("".join(f"{k}={v}\n" for k, v in self.values.items()))
        self.environment = isolated_environment(self.values)
        self.command = [
            "docker",
            "compose",
            "--project-name",
            self.project,
            "--env-file",
            str(self.env_file),
            "-f",
            str(ROOT / "compose.yaml"),
        ]
        self.api = f"http://127.0.0.1:{ports[2]}"
        self.frontend = f"http://127.0.0.1:{ports[3]}"
        self.report = {
            "project": self.project,
            "ports": {name: int(self.values[name]) for name in PORT_NAMES},
            "source_commit": self.git("rev-parse", "HEAD"),
            "checks": [],
            "tracked_changes": self.git("status", "--short"),
            "started_at": datetime.now(UTC).isoformat(),
            "result": "failed",
            "step": "initialization",
        }

    def git(self, *args):
        return subprocess.check_output(["git", *args], cwd=ROOT, text=True, timeout=15).strip()

    def redact(self, value):
        if isinstance(value, bytes):
            value = value.decode("utf-8", errors="replace")
        return str(value or "").replace(self.values["POSTGRES_PASSWORD"], "[REDACTED]")

    def compose(self, *args):
        assert_project(self.project)
        timeout = 900 if args[0] == "build" else 180
        try:
            result = subprocess.run(
                self.command + list(args),
                cwd=ROOT,
                env=self.environment,
                capture_output=True,
                text=True,
                encoding="utf-8",
                errors="replace",
                timeout=timeout,
                check=False,
            )
        except subprocess.TimeoutExpired as exc:
            self.log(args, "timeout", self.redact(exc.stdout) + self.redact(exc.stderr))
            raise RuntimeError(f"compose {args[0]} timed out after {timeout}s") from None
        self.log(args, result.returncode, result.stdout + result.stderr)
        if result.returncode:
            raise RuntimeError(
                f"compose {args[0]} failed (exit {result.returncode}); see commands.log"
            )
        return result.stdout.strip()

    def log(self, args, exit_code, output):
        with (self.directory / "commands.log").open("a", encoding="utf-8") as stream:
            stream.write(self.redact(f"compose {' '.join(args)} | exit={exit_code}\n{output}\n"))

    def expected_head(self):
        heads = json.loads(
            self.compose(
                "run",
                "--rm",
                "migrate",
                "python",
                "-c",
                "import json; from alembic.config import Config; "
                "from alembic.script import ScriptDirectory; "
                "print(json.dumps(ScriptDirectory.from_config(Config('alembic.ini')).get_heads()))",
            )
        )
        if not isinstance(heads, list) or len(heads) != 1 or not isinstance(heads[0], str):
            raise RuntimeError("Expected exactly one Alembic head")
        self.report["expected_head"] = heads[0]
        return heads[0]

    def revision(self, expected):
        if self.sql("SELECT version_num FROM alembic_version") != expected:
            raise RuntimeError("Unexpected migration revision")

    def tables(self, expected):
        actual = self.sql(
            "SELECT tablename FROM pg_tables WHERE schemaname='edu' ORDER BY tablename"
        ).splitlines()
        self.report["observed_tables"] = actual
        if actual != expected:
            raise RuntimeError(f"Unexpected edu tables: expected {expected}, observed {actual}")

    def passed(self, name):
        self.report["checks"].append(name)
        print(f"PASS {name}", flush=True)

    def sql(self, statement):
        return self.compose(
            "exec",
            "-T",
            "db",
            "psql",
            "-U",
            "eduvia_m0",
            "-d",
            "eduvia_m0",
            "-v",
            "ON_ERROR_STOP=1",
            "-Atc",
            statement,
        )

    def schema(self, expected):
        state = self.sql("SELECT count(*) FROM information_schema.schemata WHERE schema_name='edu'")
        if state != str(expected):
            raise RuntimeError("Unexpected edu schema state")
        if self.sql("SELECT count(*) FROM pg_extension WHERE extname='vector'") != "1":
            raise RuntimeError("vector extension missing")

    def healthy(self):
        wait_http(self.api + "/health/live", 200)
        wait_http(self.api + "/health/ready", 200, {"postgres": "ok", "redis": "ok"})
        body = wait_http(self.frontend + "/api/backend/health", 200)
        if json.loads(body).get("service") != "eduvia-api":
            raise RuntimeError("Proxy contract mismatch")

    def run(self):
        try:
            self.report["step"] = "build"
            # Fresh source build; no shared application image tags.
            self.compose("build")
            self.passed("current-source container production builds")
            self.compose("up", "-d", "--wait", "db", "redis")
            self.report["step"] = "bootstrap"
            if (
                self.sql("SELECT count(*) FROM information_schema.schemata WHERE schema_name='edu'")
                != "0"
            ):
                raise RuntimeError("Expected a fresh database")
            head = self.expected_head()
            self.compose("run", "--rm", "migrate", "alembic", "upgrade", "0001_bootstrap")
            self.schema(1)
            self.revision("0001_bootstrap")
            self.tables([])
            self.passed("bootstrap revision/vector/edu; no business tables")
            self.report["step"] = "upgrade-head"
            for _ in range(2):
                self.compose("run", "--rm", "migrate")
                self.revision(head)
                self.tables(IDENTITY_TABLES)
            self.passed("upgrade head twice; expected revision and identity tables")
            self.report["step"] = "downgrade-upgrade"
            self.compose("run", "--rm", "migrate", "alembic", "downgrade", "base")
            self.schema(0)
            if self.sql("SELECT count(*) FROM alembic_version") != "0":
                raise RuntimeError("Downgrade retained revision")
            self.compose("run", "--rm", "migrate")
            self.schema(1)
            self.revision(head)
            self.tables(IDENTITY_TABLES)
            self.passed("downgrade preserves vector; upgrade restores head and identity tables")
            self.report["step"] = "production-smoke"
            self.compose("up", "-d", "--wait", "api", "frontend", "worker")
            self.healthy()
            self.report["runtime_versions"] = {
                "python": self.compose("exec", "-T", "api", "python", "--version"),
                "node": self.compose("exec", "-T", "frontend", "node", "--version"),
            }
            for route in ROUTES:
                if "Eduvia" not in wait_http(self.frontend + route, 200):
                    raise RuntimeError(f"Missing shell: {route}")
            self.passed("11 production routes; direct API, readiness and proxy")
            for service, checks in (
                ("db", {"postgres": "unavailable", "redis": "ok"}),
                ("redis", {"postgres": "ok", "redis": "unavailable"}),
            ):
                self.report["step"] = f"outage-{service}"
                self.compose("stop", service)
                wait_http(self.api + "/health/live", 200)
                wait_http(self.api + "/health/ready", 503, checks)
                wait_http(self.frontend + "/api/backend/health", 200)
                self.compose("start", service)
                self.healthy()
                self.passed(f"{service} loss: live 200, ready 503; recovery ready/proxy 200")
            self.report["step"] = "outage-api"
            self.compose("stop", "api")
            started = time.monotonic()
            body = wait_http(self.frontend + "/api/backend/health", 503, seconds=15)
            elapsed = time.monotonic() - started
            if (
                elapsed > 10
                or json.loads(body).get("error", {}).get("code") != "backend_unavailable"
            ):
                raise RuntimeError("Unbounded or unexpected proxy failure")
            self.report["api_loss_seconds"] = round(elapsed, 3)
            self.compose("start", "api")
            self.healthy()
            self.passed("API loss: bounded proxy 503; restart restores 200")
            self.report["result"] = "passed"
        except Exception as exc:
            self.report["result"] = "failed"
            self.report["failed_step"] = self.report["step"]
            self.report["error"] = self.redact(exc)
        finally:
            try:
                self.compose("down", "--volumes", "--remove-orphans", "--rmi", "local")
                self.report["cleanup"] = "passed; project containers/network/volumes/images removed"
            except Exception as exc:
                self.report["cleanup"] = (
                    f"FAILED: remove only project {self.project} after inspection"
                )
                self.report["result"] = "failed"
                self.report["cleanup_error"] = self.redact(exc)
                self.report.setdefault("failed_step", "cleanup")
            self.env_file.unlink(missing_ok=True)
            self.report["finished_at"] = datetime.now(UTC).isoformat()
            (self.directory / "result.json").write_text(
                json.dumps(self.report, indent=2) + "\n", encoding="utf-8"
            )
            print(f"Evidence: {self.directory / 'result.json'}", flush=True)
        if self.report["result"] != "passed":
            raise RuntimeError("Verification or cleanup failed")


if __name__ == "__main__":
    argparse.ArgumentParser(description=__doc__).parse_args()
    Verification().run()
