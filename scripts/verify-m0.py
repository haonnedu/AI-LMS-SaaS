"""Disposable M0 migration and outage checks. Never operates on the default stack."""

import argparse
import json
import os
import re
import secrets
import socket
import subprocess
import time
from datetime import UTC, datetime
from pathlib import Path
from urllib.error import HTTPError, URLError
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
ROUTES = (
    "/",
    "/library",
    "/classes",
    "/settings",
    "/login",
    "/lessons",
    "/assessments",
    "/student",
    "/school",
    "/admin",
    "/analytics",
)


def isolated_environment(values):
    """Compose shell values otherwise override --env-file, including project/ports."""
    env = {k: v for k, v in os.environ.items() if not k.startswith("COMPOSE_")}
    for key in values:
        env.pop(key, None)
    env["COMPOSE_DISABLE_ENV_FILE"] = "1"
    return env


def free_ports(count):
    sockets = []
    try:
        for _ in range(count):
            item = socket.socket()
            sockets.append(item)
            item.bind(("127.0.0.1", 0))
        return [item.getsockname()[1] for item in sockets]
    finally:
        for item in sockets:
            item.close()


def http(url):
    try:
        with urlopen(url, timeout=8) as response:
            return response.status, response.read().decode("utf-8")
    except HTTPError as exc:
        return exc.code, exc.read().decode("utf-8")


def wait_http(url, status, checks=None, seconds=90):
    deadline = time.monotonic() + seconds
    while time.monotonic() < deadline:
        try:
            actual, body = http(url)
            if actual == status and (
                checks is None or json.loads(body).get("checks") == checks
            ):
                return body
        except (URLError, TimeoutError, ConnectionError, ValueError):
            pass
        time.sleep(1)
    raise RuntimeError(f"Expected HTTP {status} and checks={checks} at {url}")


def assert_project(project):
    if not re.fullmatch(r"eduvia-m0-\d{8}t\d{6}z-[a-f0-9]{8}", project):
        raise ValueError(
            "Refusing operation on a project not generated by this verifier"
        )


class Verification:
    def __init__(self):
        stamp = datetime.now(UTC).strftime("%Y%m%dt%H%M%Sz").lower()
        self.project = f"eduvia-m0-{stamp}-{secrets.token_hex(4)}"
        assert_project(self.project)
        self.directory = ROOT / "tmp" / self.project
        self.directory.mkdir(parents=True)
        ports = free_ports(4)
        self.values = dict(
            zip(
                ("POSTGRES_PORT", "REDIS_PORT", "API_PORT", "FRONTEND_PORT"),
                map(str, ports),
                strict=True,
            )
        )
        self.values.update(
            POSTGRES_DB="eduvia_m0",
            POSTGRES_USER="eduvia_m0",
            POSTGRES_PASSWORD=secrets.token_hex(24),
        )
        self.env_file = self.directory / "compose.env"
        self.env_file.write_text("".join(f"{k}={v}\n" for k, v in self.values.items()))
        self.environment = isolated_environment(self.values)
        self.command = [
            "docker",
            "compose",
            "--project-name",
            self.project,
            "--env-file",
            str(self.env_file),
            "-f",
            str(ROOT / "compose.yaml"),
        ]
        self.api = f"http://127.0.0.1:{ports[2]}"
        self.frontend = f"http://127.0.0.1:{ports[3]}"
        self.report = {
            "project": self.project,
            "ports": dict(zip(self.values, ports)),
            "source_commit": self.git("rev-parse", "HEAD"),
            "checks": [],
            "tracked_changes": self.git("status", "--short"),
            "started_at": datetime.now(UTC).isoformat(),
        }

    def git(self, *args):
        return subprocess.check_output(["git", *args], cwd=ROOT, text=True).strip()

    def compose(self, *args):
        assert_project(self.project)
        result = subprocess.run(
            self.command + list(args),
            cwd=ROOT,
            env=self.environment,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
        )
        # Passwords never reach saved logs, including Docker diagnostics.
        output = (result.stdout + result.stderr).replace(
            self.values["POSTGRES_PASSWORD"], "[REDACTED]"
        )
        with (self.directory / "commands.log").open("a", encoding="utf-8") as stream:
            stream.write(
                f"compose {' '.join(args)} | exit={result.returncode}\n{output}\n"
            )
        if result.returncode:
            raise RuntimeError(
                f"compose {args[0]} failed (exit {result.returncode}); see commands.log"
            )
        return result.stdout.strip()

    def passed(self, name):
        self.report["checks"].append(name)
        print(f"PASS {name}", flush=True)

    def sql(self, statement):
        return self.compose(
            "exec",
            "-T",
            "db",
            "psql",
            "-U",
            "eduvia_m0",
            "-d",
            "eduvia_m0",
            "-v",
            "ON_ERROR_STOP=1",
            "-Atc",
            statement,
        )

    def schema(self, expected):
        state = self.sql(
            "SELECT count(*) FROM information_schema.schemata WHERE schema_name='edu'"
        )
        if state != str(expected):
            raise RuntimeError("Unexpected edu schema state")
        if self.sql("SELECT count(*) FROM pg_extension WHERE extname='vector'") != "1":
            raise RuntimeError("vector extension missing")

    def healthy(self):
        wait_http(self.api + "/health/live", 200)
        wait_http(self.api + "/health/ready", 200, {"postgres": "ok", "redis": "ok"})
        body = wait_http(self.frontend + "/api/backend/health", 200)
        if json.loads(body).get("service") != "eduvia-api":
            raise RuntimeError("Proxy contract mismatch")

    def run(self):
        try:
            # Fresh source build; no shared application image tags.
            self.compose("build")
            self.passed("current-source container production builds")
            self.compose("up", "-d", "--wait", "db", "redis")
            if (
                self.sql(
                    "SELECT count(*) FROM information_schema.schemata WHERE schema_name='edu'"
                )
                != "0"
            ):
                raise RuntimeError("Expected a fresh database")
            for _ in range(2):
                self.compose("run", "--rm", "migrate")
            self.schema(1)
            if self.sql("SELECT version_num FROM alembic_version") != "0001_bootstrap":
                raise RuntimeError("Unexpected migration revision")
            if (
                self.sql(
                    "SELECT count(*) FROM information_schema.tables WHERE table_schema='edu'"
                )
                != "0"
            ):
                raise RuntimeError("Unexpected business tables")
            self.passed(
                "empty DB upgrade twice; revision/vector/edu; no business tables"
            )
            self.compose("run", "--rm", "migrate", "alembic", "downgrade", "base")
            self.schema(0)
            if self.sql("SELECT count(*) FROM alembic_version") != "0":
                raise RuntimeError("Downgrade retained revision")
            self.compose("run", "--rm", "migrate")
            self.schema(1)
            self.passed("downgrade preserves vector; upgrade restores edu")
            self.compose("up", "-d", "--wait", "api", "frontend", "worker")
            self.healthy()
            self.report["runtime_versions"] = {
                "python": self.compose("exec", "-T", "api", "python", "--version"),
                "node": self.compose("exec", "-T", "frontend", "node", "--version"),
            }
            for route in ROUTES:
                if "Eduvia" not in wait_http(self.frontend + route, 200):
                    raise RuntimeError(f"Missing shell: {route}")
            self.passed("11 production routes; direct API, readiness and proxy")
            for service, checks in (
                ("db", {"postgres": "unavailable", "redis": "ok"}),
                ("redis", {"postgres": "ok", "redis": "unavailable"}),
            ):
                self.compose("stop", service)
                wait_http(self.api + "/health/live", 200)
                wait_http(self.api + "/health/ready", 503, checks)
                wait_http(self.frontend + "/api/backend/health", 200)
                self.compose("start", service)
                self.healthy()
                self.passed(
                    f"{service} loss: live 200, ready 503; recovery ready/proxy 200"
                )
            self.compose("stop", "api")
            started = time.monotonic()
            body = wait_http(self.frontend + "/api/backend/health", 503, seconds=15)
            elapsed = time.monotonic() - started
            if (
                elapsed > 10
                or json.loads(body).get("error", {}).get("code")
                != "backend_unavailable"
            ):
                raise RuntimeError("Unbounded or unexpected proxy failure")
            self.report["api_loss_seconds"] = round(elapsed, 3)
            self.compose("start", "api")
            self.healthy()
            self.passed("API loss: bounded proxy 503; restart restores 200")
            self.report["result"] = "passed"
        except Exception as exc:
            self.report["result"] = "failed"
            self.report["error"] = str(exc)
            raise
        finally:
            try:
                self.compose("down", "--volumes", "--remove-orphans", "--rmi", "local")
                self.report["cleanup"] = (
                    "passed; project containers/network/volumes/images removed"
                )
            except Exception:
                self.report["cleanup"] = (
                    f"FAILED: remove only project {self.project} after inspection"
                )
                self.report["result"] = "failed"
            self.env_file.unlink(missing_ok=True)
            self.report["finished_at"] = datetime.now(UTC).isoformat()
            (self.directory / "result.json").write_text(
                json.dumps(self.report, indent=2) + "\n", encoding="utf-8"
            )
            print(f"Evidence: {self.directory / 'result.json'}", flush=True)
        if self.report["result"] != "passed":
            raise RuntimeError("Verification or cleanup failed")


if __name__ == "__main__":
    argparse.ArgumentParser(description=__doc__).parse_args()
    Verification().run()
