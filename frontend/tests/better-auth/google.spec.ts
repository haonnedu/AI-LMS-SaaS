import { expect, test } from "@playwright/test";
import { createClient } from "redis";
import { createHash } from "node:crypto";
import { decryptStorage } from "../../src/lib/server/better-storage";
import { resetRates } from "./reset-rates";
test.beforeEach(resetRates);

test("Google link requires two proofs and confirmation, preserves workspace, and can be unlinked", async ({ page, request, context, playwright }) => {
  const origin = "http://127.0.0.1:3106", email = `linked-${Date.now()}@example.test`, password = "Linked-password-2026!";
  const googleId = "link-" + Date.now();
  await request.post("http://127.0.0.1:9112/identity", { data: { sub: googleId, email, email_verified: true } });
  await page.route("https://accounts.google.com/**", async route => {
    const url = new URL(route.request().url());
    const response = await request.get("http://127.0.0.1:9112/authorize" + url.search, { maxRedirects: 0 });
    await route.fulfill({ status: 302, headers: { Location: response.headers().location }, body: "" });
  });
  const signup = await request.post("/api/auth/sign-up/email", { headers: { Origin: origin }, data: { email, password, name: "Linked Teacher", callbackURL: "/login" } });
  expect(signup.status()).toBe(200);
  const messages: string[] = await (await request.get("http://127.0.0.1:9112")).json();
  const decoded = messages.filter(m => m.includes(email)).at(-1)!.replace(/=\r?\n/g, "").replace(/=([0-9A-F]{2})/g, (_, hex) => String.fromCharCode(parseInt(hex, 16)));
  const verification = decoded.match(/http:\/\/127\.0\.0\.1:3106\/api\/auth\/verify-email[^\s<>]*/)![0];
  await page.goto(verification);
  await page.goto("/login");
  await page.getByLabel("Email", { exact: true }).fill(email);
  await page.getByLabel("Mật khẩu", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Tiếp tục", exact: true }).click();
  await expect(page).toHaveURL(/\/onboarding$/);
  await page.getByRole("checkbox", { name: /Tôi đã đọc và đồng ý/ }).check();
  await page.getByRole("button", { name: "Mở workspace cá nhân" }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  const previousUser = await (await page.request.get("/api/backend/me")).json();
  const previousWorkspaces = await (await page.request.get("/api/backend/workspaces")).json();
  await page.goto("/account");
  await page.getByRole("button", { name: "Liên kết Google", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("xác thực lại");
  await page.getByLabel("Xác thực lại bằng mật khẩu").fill(password);
  await page.getByRole("button", { name: "Xác thực lại", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Đã xác thực lại");
  await request.post("http://127.0.0.1:9112/identity", { data: { sub: googleId + "-wrong", email: "different-" + email, email_verified: true } });
  await page.getByRole("button", { name: "Liên kết Google", exact: true }).click();
  await expect(page).toHaveURL(/\/account\?.*error/);
  await expect(page.getByRole("status")).toContainText("Chưa thể liên kết Google");
  expect((await (await page.request.get("/api/account")).json()).methods.google).toBe(false);
  await request.post("http://127.0.0.1:9112/identity", { data: { sub: googleId, email, email_verified: true } });
  await page.getByRole("button", { name: "Liên kết Google", exact: true }).click();
  await expect(page).toHaveURL(/confirm=google/);
  // Native callback has proved Google ownership, but has not attached it yet.
  expect((await (await page.request.get("/api/account")).json()).methods.google).toBe(false);
  const oldState = await context.storageState();
  const cookie = oldState.cookies.find(cookie => cookie.name.endsWith(".session_token"))!;
  const token = decodeURIComponent(cookie.value).split(".")[0];
  const connection = createClient({ url: "redis://127.0.0.1:6381/3" });
  await connection.connect();
  const oldRecord = (await connection.get("eduvia:ba:" + token))!;
  process.env.SESSION_ENCRYPTION_KEY = "c".repeat(64);
  const authId = JSON.parse(decryptStorage(token, oldRecord)).user.id;
  await page.getByRole("button", { name: "Xác nhận liên kết Google", exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  // Simulate Redis recovering an old session after a credential mutation.
  // The durable database marker must deny it even without Redis's user epoch.
  await connection.set("eduvia:ba:" + token, oldRecord, { EX: 300 });
  await connection.del("eduvia:ba:user-revoked-before:" + createHash("sha256").update(authId).digest("hex"));
  const stale = await playwright.request.newContext({ storageState: oldState });
  expect((await (await stale.get(origin + "/api/session")).json()).authenticated).toBe(false);
  await stale.dispose();
  await connection.del("eduvia:ba:" + token);
  await connection.close();
  await page.getByRole("button", { name: "Đăng nhập bằng Google", exact: true }).click();
  await expect(page).toHaveURL(/\/onboarding$/);
  await page.getByRole("button", { name: "Mở workspace cá nhân" }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  expect((await (await page.request.get("/api/backend/me")).json()).id).toEqual(previousUser.id);
  expect(await (await page.request.get("/api/backend/workspaces")).json()).toEqual(previousWorkspaces);
  await page.goto("/account");
  await page.getByLabel("Xác thực lại bằng mật khẩu").fill(password);
  await page.getByRole("button", { name: "Xác thực lại", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Đã xác thực lại");
  await page.getByRole("button", { name: "Hủy liên kết Google và đăng xuất" }).click();
  await expect(page).toHaveURL(/\/login$/);
});
