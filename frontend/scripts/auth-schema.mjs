import { getAuthTables } from 'better-auth/db';
import { jwt } from 'better-auth/plugins';
import { writeFileSync } from 'node:fs';

const q = s => '"' + s + '"';
let sql = '-- Better Auth 1.7.12 core + JWT: generated by frontend/scripts/auth-schema.mjs\n';
for (const [name, table] of Object.entries(getAuthTables({ plugins: [jwt()] }))) {
  const fields = ['id text PRIMARY KEY'];
  for (const [key, field] of Object.entries(table.fields)) {
    const type = { string: 'text', boolean: 'boolean', date: 'timestamptz', number: 'integer' }[field.type];
    if (!type) throw Error('Unsupported schema type');
    let definition = q(field.fieldName || key) + ' ' + type + (field.required ? ' NOT NULL' : '') + (field.unique ? ' UNIQUE' : '');
    if (field.references) definition += ' REFERENCES auth.' + q(field.references.model) + '(' + q(field.references.field) + ') ON DELETE CASCADE';
    fields.push(definition);
  }
  sql += 'CREATE TABLE auth.' + q(table.modelName || name) + ' (\n' + fields.join(',\n') + '\n);\n';
  for (const [key, field] of Object.entries(table.fields)) if (field.index) sql += 'CREATE INDEX ON auth.' + q(table.modelName || name) + ' (' + q(field.fieldName || key) + ');\n';
}
sql += 'CREATE UNIQUE INDEX account_provider_identity ON auth.account ("providerId", "accountId");\n';
sql += 'CREATE UNIQUE INDEX one_google_per_user ON auth.account ("userId") WHERE "providerId"=\'google\';\n';
writeFileSync(new URL('../../backend/migrations/sql/better-auth-1.7.12.sql', import.meta.url), sql);
